export function buildLegalTokens(
  settings: Record<string, string>,
  legal: LegalInfo,
): Record<string, string> {
  return {
    operator_name: legal.operatorName,
    inn: legal.inn,
    ogrn: legal.ogrn,
    address: legal.address,
    email: legal.email,
    phone: settings.phone || "уточняется",
    updated: legal.updated,
  };
}

